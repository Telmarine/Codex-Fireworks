        g('R', "#### ", "#   #", "#   #", "#### ", "# #  ", "#  # ", "#   #");
        g('S', " ####", "#    ", "#    ", " ### ", "    #", "    #", "#### ");
        g('T', "#####", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ");
